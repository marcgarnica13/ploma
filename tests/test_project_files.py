def test_rules_have_paths_frontmatter_and_no_domain_words(sample_paper, cfg):
    specs = {s.path: s.content for s in project_files.render_all(cfg, sample_paper)}
    globs, body = _frontmatter_paths(specs[MANUSCRIPT])
    assert globs == ["**/*.tex", "refs.bib"]
    assert body[0] == GENERATED_LINE
    text = specs[MANUSCRIPT]
    assert "pdflatex" in text and "bibtex" in text and "article" in text and "numeric" in text
    assert "Anonymized submission: yes" in text and "Em-dash forbidden: yes" in text
    assert "Facts live in ploma.yaml, do not restate them here" in text
    pglobs, pbody = _frontmatter_paths(specs[PIPELINE])
    assert pglobs == ["**"] and pbody[0] == GENERATED_LINE
    assert "avg_fitness, n_teams" in specs[PIPELINE] and "metrics 0.01" in specs[PIPELINE]
    for path in (MANUSCRIPT, PIPELINE):
        assert not BANNED_RE.search(specs[path]), path
        assert not LLNCS_RE.search(specs[path]), path
        assert not EM_DASH_RE.search(specs[path]), path
        assert "{{" not in specs[path] and "}}" not in specs[path]


