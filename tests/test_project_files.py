MANUSCRIPT = ".claude/rules/ploma-manuscript.md"
PIPELINE = ".claude/rules/ploma-pipeline.md"
GENERATED_LINE = "<!-- generated by ploma from ploma.yaml; edit ploma.yaml, not this file -->"


def _apply(root, cfg):
    return project_files.apply(root, cfg, project_files.plan(root, cfg))


def _actions(root, cfg):
    return {p["path"]: p["action"] for p in project_files.plan(root, cfg)}


def _doctor(root):
    return doctor.run(root, which=lambda n: "/usr/bin/" + n, home=root / "nohome")


def _ids(r):
    return {f.id: f for g in r.groups for f in g["findings"]}


def _frontmatter_paths(text):
    lines = text.splitlines()
    assert lines[0] == "---"
    end = lines.index("---", 1)
    assert lines[1] == "paths:"
    globs = []
    for ln in lines[2:end]:
        assert ln.startswith("  - "), ln
        globs.append(json.loads(ln[4:]))
    return globs, lines[end + 1:]


